import React, { useState } from 'react';
import { useQuery, useQueryClient } from '@tanstack/react-query';
import { ShieldAlert, CheckCircle, AlertTriangle, UserCheck, Search, Filter } from 'lucide-react';
import { riskApi, adminApi } from '@/api/client';
import { Card, Button, Badge, Modal, Input, Spinner, EmptyState } from '@/components/UI';

export const RiskAlerts: React.FC = () => {
  const queryClient = useQueryClient();
  const [statusFilter, setStatusFilter] = useState('');
  const [severityFilter, setSeverityFilter] = useState('');
  const [selectedAlert, setSelectedAlert] = useState<any>(null);
  const [resolveStatus, setResolveStatus] = useState<'resolved' | 'false_positive'>('resolved');
  const [notes, setNotes] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  const { data: alerts, isLoading } = useQuery({
    queryKey: ['fraud_alerts', statusFilter, severityFilter],
    queryFn: async () => {
      const res = await riskApi.getAlerts({
        status: statusFilter || undefined,
        severity: severityFilter || undefined,
        per_page: 50,
      });
      return res.data;
    },
  });

  const { data: analysts } = useQuery({
    queryKey: ['analysts_list'],
    queryFn: async () => (await adminApi.getUsers({ role: 'risk_analyst' })).data,
  });

  const handleOpenResolve = (alert: any) => {
    setSelectedAlert(alert);
    setResolveStatus('resolved');
    setNotes('Verified transaction pattern and confirmed resolution');
    setError('');
  };

  const handleResolveSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!selectedAlert) return;

    setLoading(true);
    setError('');
    try {
      await riskApi.resolveAlert(selectedAlert.id, {
        status: resolveStatus,
        notes: notes.trim() || undefined,
      });

      setSelectedAlert(null);
      queryClient.invalidateQueries({ queryKey: ['fraud_alerts'] });
    } catch (err: any) {
      setError(err.response?.data?.detail || 'Failed to update alert');
    } finally {
      setLoading(false);
    }
  };

  const handleAssign = async (alertId: string, analystId: string) => {
    try {
      await riskApi.assignAlert(alertId, analystId);
      queryClient.invalidateQueries({ queryKey: ['fraud_alerts'] });
    } catch (err: any) {
      alert(`Assignment failed: ${err.message}`);
    }
  };

  const severityVariant = (sev: string): 'error' | 'warning' | 'info' | 'neutral' => {
    switch (sev) {
      case 'critical':
      case 'high':
        return 'error';
      case 'medium':
        return 'warning';
      case 'low':
        return 'info';
      default:
        return 'neutral';
    }
  };

  return (
    <div className="space-y-8 animate-fade-in">
      <div>
        <h1 className="text-2xl font-bold tracking-tight text-gray-900 dark:text-gray-100 flex items-center gap-2">
          <ShieldAlert className="w-6 h-6 text-rose-600" /> Fraud Alerts Operations
        </h1>
        <p className="text-sm text-gray-500 dark:text-gray-400 mt-0.5">
          Real-time alerts generated by trigger sp_evaluate_fraud_rules
        </p>
      </div>

      {/* Filter Row */}
      <Card className="p-4">
        <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
          <div>
            <label className="block text-xs font-medium text-gray-500 mb-1">Status Filter</label>
            <select
              value={statusFilter}
              onChange={(e) => setStatusFilter(e.target.value)}
              className="w-full rounded-lg border border-gray-300 dark:border-gray-700 bg-white dark:bg-gray-900 px-3 py-2 text-sm text-gray-900 dark:text-gray-100 focus:outline-none focus:ring-2 focus:ring-indigo-500"
            >
              <option value="">All Statuses</option>
              <option value="open">Open</option>
              <option value="investigating">Investigating</option>
              <option value="resolved">Resolved</option>
              <option value="false_positive">False Positive</option>
            </select>
          </div>
          <div>
            <label className="block text-xs font-medium text-gray-500 mb-1">Severity Filter</label>
            <select
              value={severityFilter}
              onChange={(e) => setSeverityFilter(e.target.value)}
              className="w-full rounded-lg border border-gray-300 dark:border-gray-700 bg-white dark:bg-gray-900 px-3 py-2 text-sm text-gray-900 dark:text-gray-100 focus:outline-none focus:ring-2 focus:ring-indigo-500"
            >
              <option value="">All Severities</option>
              <option value="critical">Critical</option>
              <option value="high">High</option>
              <option value="medium">Medium</option>
              <option value="low">Low</option>
            </select>
          </div>
        </div>
      </Card>

      {/* Alerts Table */}
      <Card title={`Active Alerts (${alerts?.length || 0})`}>
        {isLoading ? (
          <Spinner />
        ) : !alerts || alerts.length === 0 ? (
          <EmptyState
            title="No alerts matching filters"
            description="The fraud rules engine has not flagged any transactions under these filters."
            icon={<ShieldAlert className="w-6 h-6" />}
          />
        ) : (
          <div className="overflow-x-auto -mx-6">
            <table className="w-full text-left border-collapse text-sm">
              <thead>
                <tr className="border-b border-gray-200 dark:border-gray-700 text-xs font-semibold text-gray-500 dark:text-gray-400 bg-gray-50/50 dark:bg-gray-800/50">
                  <th className="py-3 px-6">Timestamp</th>
                  <th className="py-3 px-6">Rule Code</th>
                  <th className="py-3 px-6">Severity</th>
                  <th className="py-3 px-6">Account ID</th>
                  <th className="py-3 px-6">Assigned Analyst</th>
                  <th className="py-3 px-6">Status</th>
                  <th className="py-3 px-6 text-right">Actions</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-gray-100 dark:divide-gray-800">
                {alerts.map((al: any) => {
                  const isOpen = al.status === 'open' || al.status === 'investigating';
                  return (
                    <tr key={al.id} className="hover:bg-gray-50/50 dark:hover:bg-gray-800/50">
                      <td className="py-3.5 px-6 text-xs text-gray-500 whitespace-nowrap">
                        {new Date(al.created_at).toLocaleString()}
                      </td>
                      <td className="py-3.5 px-6">
                        <span className="font-mono text-xs font-bold text-gray-900 dark:text-gray-100">
                          {al.rule_code || 'FRAUD_RULE'}
                        </span>
                      </td>
                      <td className="py-3.5 px-6">
                        <Badge variant={severityVariant(al.severity)}>
                          {al.severity.toUpperCase()}
                        </Badge>
                      </td>
                      <td className="py-3.5 px-6 font-mono text-xs text-gray-400">
                        {al.account_id?.slice(0, 8)}...
                      </td>
                      <td className="py-3.5 px-6">
                        {isOpen ? (
                          <select
                            value={al.assigned_to || ''}
                            onChange={(e) => handleAssign(al.id, e.target.value)}
                            className="text-xs rounded border border-gray-200 dark:border-gray-700 bg-white dark:bg-gray-800 p-1 text-gray-700 dark:text-gray-300"
                          >
                            <option value="">Unassigned</option>
                            {analysts?.map((an: any) => (
                              <option key={an.id} value={an.id}>
                                {an.full_name}
                              </option>
                            ))}
                          </select>
                        ) : (
                          <span className="text-xs text-gray-500">{al.assigned_name || '—'}</span>
                        )}
                      </td>
                      <td className="py-3.5 px-6">
                        <Badge variant={isOpen ? 'warning' : 'neutral'}>
                          {al.status.toUpperCase()}
                        </Badge>
                      </td>
                      <td className="py-3.5 px-6 text-right">
                        {isOpen && (
                          <Button
                            size="sm"
                            variant="outline"
                            onClick={() => handleOpenResolve(al)}
                            className="text-xs py-1 px-3"
                          >
                            Resolve
                          </Button>
                        )}
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}
      </Card>

      {/* Resolve Modal */}
      <Modal
        isOpen={!!selectedAlert}
        onClose={() => setSelectedAlert(null)}
        title="Resolve Fraud Investigation"
      >
        {selectedAlert && (
          <form onSubmit={handleResolveSubmit} className="space-y-4">
            {error && (
              <div className="p-3 rounded-lg bg-rose-50 text-xs text-rose-700 flex items-center gap-2">
                <AlertTriangle className="w-4 h-4 flex-shrink-0" />
                <span>{error}</span>
              </div>
            )}

            <div>
              <label className="block text-xs font-medium text-gray-500 mb-1">Investigation Outcome</label>
              <div className="grid grid-cols-2 gap-3">
                <button
                  type="button"
                  onClick={() => setResolveStatus('resolved')}
                  className={`py-2 px-3 rounded-xl border text-xs font-semibold ${
                    resolveStatus === 'resolved'
                      ? 'border-emerald-600 bg-emerald-50 dark:bg-emerald-950 text-emerald-700'
                      : 'border-gray-200 text-gray-600'
                  }`}
                >
                  Confirm Fraud (Resolved)
                </button>
                <button
                  type="button"
                  onClick={() => setResolveStatus('false_positive')}
                  className={`py-2 px-3 rounded-xl border text-xs font-semibold ${
                    resolveStatus === 'false_positive'
                      ? 'border-indigo-600 bg-indigo-50 dark:bg-indigo-950 text-indigo-700'
                      : 'border-gray-200 text-gray-600'
                  }`}
                >
                  False Positive
                </button>
              </div>
            </div>

            <Input
              label="Analyst Resolution Notes"
              value={notes}
              onChange={(e) => setNotes(e.target.value)}
              placeholder="Detail reasons for resolution..."
              required
            />

            <div className="pt-2 flex justify-end gap-3">
              <Button type="button" variant="outline" onClick={() => setSelectedAlert(null)}>
                Cancel
              </Button>
              <Button type="submit" isLoading={loading}>
                Save Decision
              </Button>
            </div>
          </form>
        )}
      </Modal>
    </div>
  );
};
