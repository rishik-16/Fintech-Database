import React, { useState } from 'react';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { Scale, Upload, Play, CheckCircle2, AlertTriangle, FileSpreadsheet, Layers } from 'lucide-react';
import { riskApi } from '@/api/client';
import { Card, Button, Badge, Spinner, EmptyState } from '@/components/UI';

export const Reconciliation: React.FC = () => {
  const queryClient = useQueryClient();
  const [selectedFile, setSelectedFile] = useState<File | null>(null);
  const [uploading, setUploading] = useState(false);
  const [selectedRunId, setSelectedRunId] = useState<string | null>(null);
  const [reconcilingId, setReconcilingId] = useState<string | null>(null);
  const [activeTab, setActiveTab] = useState<'matched' | 'unmatched' | 'amount_mismatch'>('matched');

  const { data: imports, isLoading: importsLoading } = useQuery({
    queryKey: ['bank_imports'],
    queryFn: async () => (await riskApi.getImports()).data,
  });

  const { data: runDetails, isLoading: runLoading } = useQuery({
    queryKey: ['recon_details', selectedRunId],
    enabled: !!selectedRunId,
    queryFn: async () => (await riskApi.getReconciliation(selectedRunId!)).data,
  });

  const handleFileUpload = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!selectedFile) return;

    setUploading(true);
    const formData = new FormData();
    formData.append('file', selectedFile);

    try {
      await riskApi.importStatement(formData);
      setSelectedFile(null);
      queryClient.invalidateQueries({ queryKey: ['bank_imports'] });
    } catch (err: any) {
      alert(`Upload failed: ${err.response?.data?.detail || err.message}`);
    } finally {
      setUploading(false);
    }
  };

  const handleRunReconcile = async (importId: string) => {
    setReconcilingId(importId);
    try {
      const res = await riskApi.reconcile(importId);
      queryClient.invalidateQueries({ queryKey: ['bank_imports'] });
      if (res.data?.id) {
        setSelectedRunId(res.data.id);
      }
    } catch (err: any) {
      alert(`Reconciliation failed: ${err.response?.data?.detail || err.message}`);
    } finally {
      setReconcilingId(null);
    }
  };

  const lines = runDetails?.lines || [];
  const filteredLines = lines.filter((l: any) => l.match_status === activeTab);

  return (
    <div className="space-y-8 animate-fade-in">
      <div>
        <h1 className="text-2xl font-bold tracking-tight text-gray-900 dark:text-gray-100 flex items-center gap-2">
          <Scale className="w-6 h-6 text-indigo-600" /> Bank Statement Reconciliation
        </h1>
        <p className="text-sm text-gray-500 dark:text-gray-400 mt-0.5">
          Automated reference and amount matching engine powered by stored procedure sp_reconcile
        </p>
      </div>

      {/* Upload Box */}
      <Card title="Import Bank Statement (CSV)" subtitle="Upload mock CSV to reconcile counterparty bank entries">
        <form onSubmit={handleFileUpload} className="flex flex-col sm:flex-row items-center gap-4 pt-2">
          <input
            type="file"
            accept=".csv"
            onChange={(e) => setSelectedFile(e.target.files?.[0] || null)}
            className="block w-full text-sm text-gray-500 file:mr-4 file:py-2 file:px-4 file:rounded-lg file:border-0 file:text-xs file:font-semibold file:bg-indigo-50 file:text-indigo-700 hover:file:bg-indigo-100 dark:file:bg-indigo-950 dark:file:text-indigo-300"
          />
          <Button type="submit" disabled={!selectedFile} isLoading={uploading} className="whitespace-nowrap flex items-center gap-1.5">
            <Upload className="w-4 h-4" /> Import CSV
          </Button>
        </form>
      </Card>

      {/* Past Statement Imports Table */}
      <Card title="Statement Imports & Reconciliation Status" subtitle="Summary view from payledger.v_reconciliation_summary">
        {importsLoading ? (
          <Spinner />
        ) : !imports || imports.length === 0 ? (
          <EmptyState
            title="No statement imports yet"
            description="Upload the mock CSV file generated by make seed to test reconciliation."
            icon={<FileSpreadsheet className="w-6 h-6" />}
          />
        ) : (
          <div className="overflow-x-auto -mx-6">
            <table className="w-full text-left border-collapse text-sm">
              <thead>
                <tr className="border-b border-gray-200 dark:border-gray-700 text-xs font-semibold text-gray-500 dark:text-gray-400 bg-gray-50/50 dark:bg-gray-800/50">
                  <th className="py-3 px-6">Import Date</th>
                  <th className="py-3 px-6">Filename</th>
                  <th className="py-3 px-6 text-right">Total Rows</th>
                  <th className="py-3 px-6 text-right">Matched</th>
                  <th className="py-3 px-6 text-right">Mismatched</th>
                  <th className="py-3 px-6 text-right">Unmatched</th>
                  <th className="py-3 px-6">Match Rate</th>
                  <th className="py-3 px-6 text-right">Actions</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-gray-100 dark:divide-gray-800">
                {imports.map((imp: any) => (
                  <tr key={imp.import_id} className="hover:bg-gray-50/50 dark:hover:bg-gray-800/50">
                    <td className="py-3.5 px-6 text-xs text-gray-500 whitespace-nowrap">
                      {new Date(imp.imported_at).toLocaleString()}
                    </td>
                    <td className="py-3.5 px-6 font-medium text-gray-900 dark:text-gray-100">
                      {imp.filename}
                    </td>
                    <td className="py-3.5 px-6 text-right font-mono text-xs">{imp.total_lines}</td>
                    <td className="py-3.5 px-6 text-right font-semibold text-emerald-600 dark:text-emerald-400">
                      {imp.matched_count}
                    </td>
                    <td className="py-3.5 px-6 text-right font-semibold text-amber-600 dark:text-amber-400">
                      {imp.mismatch_count}
                    </td>
                    <td className="py-3.5 px-6 text-right font-semibold text-rose-600 dark:text-rose-400">
                      {imp.unmatched_count}
                    </td>
                    <td className="py-3.5 px-6">
                      <div className="flex items-center gap-2">
                        <div className="w-16 h-2 rounded-full bg-gray-200 dark:bg-gray-700 overflow-hidden">
                          <div
                            className="h-full bg-emerald-500 rounded-full"
                            style={{ width: `${imp.match_rate_pct}%` }}
                          />
                        </div>
                        <span className="text-xs font-semibold">{imp.match_rate_pct}%</span>
                      </div>
                    </td>
                    <td className="py-3.5 px-6 text-right">
                      <Button
                        size="sm"
                        variant="primary"
                        isLoading={reconcilingId === imp.import_id}
                        onClick={() => handleRunReconcile(imp.import_id)}
                        className="text-xs py-1 px-3 flex items-center gap-1"
                      >
                        <Play className="w-3 h-3 fill-white" /> Reconcile
                      </Button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Card>

      {/* Reconciliation Run Results View */}
      {selectedRunId && (
        <Card title="Reconciliation Run Breakdown" subtitle={`Run ID: ${selectedRunId}`}>
          {/* Tabs */}
          <div className="flex gap-2 border-b border-gray-200 dark:border-gray-700 mb-6">
            <button
              onClick={() => setActiveTab('matched')}
              className={`pb-2.5 px-4 text-xs font-semibold border-b-2 transition-colors ${
                activeTab === 'matched'
                  ? 'border-emerald-500 text-emerald-600 dark:text-emerald-400'
                  : 'border-transparent text-gray-500 hover:text-gray-700'
              }`}
            >
              Matched Rows ({runDetails?.run?.matched_count || 0})
            </button>
            <button
              onClick={() => setActiveTab('amount_mismatch')}
              className={`pb-2.5 px-4 text-xs font-semibold border-b-2 transition-colors ${
                activeTab === 'amount_mismatch'
                  ? 'border-amber-500 text-amber-600 dark:text-amber-400'
                  : 'border-transparent text-gray-500 hover:text-gray-700'
              }`}
            >
              Amount Mismatch ({runDetails?.run?.mismatch_count || 0})
            </button>
            <button
              onClick={() => setActiveTab('unmatched')}
              className={`pb-2.5 px-4 text-xs font-semibold border-b-2 transition-colors ${
                activeTab === 'unmatched'
                  ? 'border-rose-500 text-rose-600 dark:text-rose-400'
                  : 'border-transparent text-gray-500 hover:text-gray-700'
              }`}
            >
              Unmatched ({runDetails?.run?.unmatched_count || 0})
            </button>
          </div>

          {/* Breakdown Table */}
          {runLoading ? (
            <Spinner />
          ) : (
            <div className="overflow-x-auto -mx-6">
              <table className="w-full text-left border-collapse text-sm">
                <thead>
                  <tr className="border-b border-gray-200 dark:border-gray-700 text-xs font-semibold text-gray-500 dark:text-gray-400 bg-gray-50/50 dark:bg-gray-800/50">
                    <th className="py-3 px-6">Bank Reference</th>
                    <th className="py-3 px-6">Value Date</th>
                    <th className="py-3 px-6 text-right">Bank Amount</th>
                    <th className="py-3 px-6">Narration</th>
                    <th className="py-3 px-6">Matched Transaction UUID</th>
                    <th className="py-3 px-6">Status</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-gray-100 dark:divide-gray-800">
                  {filteredLines.map((l: any) => (
                    <tr key={l.id} className="hover:bg-gray-50/50 dark:hover:bg-gray-800/50">
                      <td className="py-3.5 px-6 font-mono text-xs">{l.bank_reference || '—'}</td>
                      <td className="py-3.5 px-6 text-xs text-gray-500">{l.value_date}</td>
                      <td className="py-3.5 px-6 text-right font-bold text-gray-900 dark:text-gray-100">
                        ₹{parseFloat(l.amount || '0').toFixed(2)}
                      </td>
                      <td className="py-3.5 px-6 text-xs text-gray-600 dark:text-gray-300 max-w-xs truncate">
                        {l.narration}
                      </td>
                      <td className="py-3.5 px-6 font-mono text-xs text-indigo-600 dark:text-indigo-400">
                        {l.matched_transaction_id ? `${l.matched_transaction_id.slice(0, 16)}...` : 'None'}
                      </td>
                      <td className="py-3.5 px-6">
                        <Badge
                          variant={
                            l.match_status === 'matched'
                              ? 'success'
                              : l.match_status === 'amount_mismatch'
                              ? 'warning'
                              : 'error'
                          }
                        >
                          {l.match_status.toUpperCase()}
                        </Badge>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </Card>
      )}
    </div>
  );
};
