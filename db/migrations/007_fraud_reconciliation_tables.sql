-- ============================================================================
-- Fraud Rules — configurable rule definitions with JSONB thresholds
-- ============================================================================
CREATE TABLE IF NOT EXISTS payledger.fraud_rules (
    id              UUID                    DEFAULT gen_random_uuid() PRIMARY KEY,
    code            VARCHAR(50)             NOT NULL,
    description     TEXT,
    threshold_json  JSONB                   NOT NULL,
    severity        payledger.alert_severity NOT NULL DEFAULT 'medium',
    active          BOOLEAN                 NOT NULL DEFAULT true,
    created_at      TIMESTAMPTZ             NOT NULL DEFAULT now(),

    CONSTRAINT uq_fraud_rule_code UNIQUE (code)
);

COMMENT ON TABLE payledger.fraud_rules IS
    'Configurable fraud detection rules. Thresholds stored as JSONB for flexibility.';

-- ============================================================================
-- Fraud Alerts — raised when a rule fires
-- ============================================================================
CREATE TABLE IF NOT EXISTS payledger.fraud_alerts (
    id                      UUID                    DEFAULT gen_random_uuid() PRIMARY KEY,
    rule_id                 UUID                    REFERENCES payledger.fraud_rules (id),
    ledger_transaction_id   UUID                    REFERENCES payledger.ledger_transactions (id),
    account_id              UUID                    REFERENCES payledger.accounts (id),
    severity                payledger.alert_severity NOT NULL,
    status                  payledger.alert_status  NOT NULL DEFAULT 'open',
    assigned_to             UUID                    REFERENCES payledger.users (id),
    created_at              TIMESTAMPTZ             NOT NULL DEFAULT now(),
    resolved_at             TIMESTAMPTZ,
    notes                   TEXT,

    -- Prevent duplicate alerts for the same rule + transaction combination
    CONSTRAINT uq_fraud_alert_rule_txn UNIQUE (rule_id, ledger_transaction_id)
);

COMMENT ON TABLE payledger.fraud_alerts IS
    'Alerts generated by the fraud rules engine, awaiting investigation.';

-- ============================================================================
-- Bank Statement Imports — for reconciliation
-- ============================================================================
CREATE TABLE IF NOT EXISTS payledger.bank_statement_imports (
    id              UUID            DEFAULT gen_random_uuid() PRIMARY KEY,
    filename        VARCHAR(500)    NOT NULL,
    imported_at     TIMESTAMPTZ     NOT NULL DEFAULT now(),
    imported_by     UUID            REFERENCES payledger.users (id)
);

-- ============================================================================
-- Bank Statement Lines — individual rows from an imported statement
-- ============================================================================
CREATE TABLE IF NOT EXISTS payledger.bank_statement_lines (
    id                      UUID                    DEFAULT gen_random_uuid() PRIMARY KEY,
    import_id               UUID                    NOT NULL
                                REFERENCES payledger.bank_statement_imports (id),
    bank_reference          VARCHAR(100),
    value_date              DATE,
    amount                  NUMERIC(18,2),
    narration               TEXT,
    matched_transaction_id  UUID                    REFERENCES payledger.ledger_transactions (id),
    match_status            payledger.match_status  NOT NULL DEFAULT 'unmatched'
);

-- ============================================================================
-- Reconciliation Runs — summary of each reconciliation execution
-- ============================================================================
CREATE TABLE IF NOT EXISTS payledger.reconciliation_runs (
    id              UUID            DEFAULT gen_random_uuid() PRIMARY KEY,
    import_id       UUID            REFERENCES payledger.bank_statement_imports (id),
    run_at          TIMESTAMPTZ     NOT NULL DEFAULT now(),
    matched_count   INT             NOT NULL DEFAULT 0,
    unmatched_count INT             NOT NULL DEFAULT 0,
    mismatch_count  INT             NOT NULL DEFAULT 0,
    run_by          UUID            REFERENCES payledger.users (id)
);
